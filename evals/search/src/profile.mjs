const SEARCH_EVAL_PRESET_META = `name: 搜索测评模式\ndescription: 仅保留网页检索与回答能力，禁用文件、Shell、Skills、Canvas、目标、计划、子代理和工作流。\norder: 100\n`;

export function baseDshHome() {
  return process.env.DSH_HOME || join(homedir(), ".dsh");
}

export function targetHome(baseHome, conditionId) {
  const safe = String(conditionId).replace(/[^A-Za-z0-9._-]+/gu, "-");
  if (!safe) throw new Error("conditionId 不能为空");
  return join(baseHome, "search-eval-targets", safe);
}

export function prepareTargetHome(baseHome, conditionId, options = {}) {
  const root = resolve(baseHome, "search-eval-targets");
  const dir = resolve(targetHome(baseHome, conditionId));
  assertInside(dir, root);
  if (options.fresh && existsSync(dir)) rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const name of ["settings.yaml", ".anonymous-user-id"]) {
    const source = join(baseHome, name);
    const destination = join(dir, name);
    if (existsSync(source) && !existsSync(destination)) copyFileSync(source, destination);
  }
  copyCredentialSubset(baseHome, dir, options.credentialRefs ?? []);
  return dir;
}

export function ensureProfile(home, name, bundles, profilePatch = null) {
  const dir = join(home, "profiles", name);
  mkdirSync(dir, { recursive: true });
  const manifest = {
    name: `dsh-profile-${name}`,
    private: true,
    dependencies: {},
    dsh: { profile: { bundles: [...new Set(bundles)] } },
  };
  writeFileSync(join(dir, "package.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(join(dir, "pnpm-workspace.yaml"), PNPM_WORKSPACE);
  if (profilePatch) writeFileSync(join(dir, "cordis.patch.yml"), toPatchYaml(profilePatch));
  return { home, name, dir };
}

export function ensureSearchEvalPreset(home, id = "search-eval") {
  const safe = String(id).replace(/[^A-Za-z0-9._-]+/gu, "-");
  if (!safe || safe !== id) throw new Error(`非法 agent preset id: ${id}`);
  const root = resolve(home, ".agent-presets");
  const dir = resolve(root, safe);
  assertInside(dir, root);
  mkdirSync(dir, { recursive: true });
  const agentPath = join(dir, "agent.cordis.yml");
  const metaPath = join(dir, "preset.yml");
  writeFileSync(agentPath, SEARCH_EVAL_PRESET);
  writeFileSync(metaPath, SEARCH_EVAL_PRESET_META);
  return {
    id: safe,
    dir,
    sha256: createHash("sha256").update(SEARCH_EVAL_PRESET).digest("hex"),
  };
}

export function ensureTaskWorkspace(home, taskId, attempt = 1) {
  const root = resolve(home, "search-eval-workspaces");
  const dir = resolve(root, `${taskId}-attempt-${attempt}`);
  assertInside(dir, root);
  if (existsSync(dir)) rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, ".search-eval-workspace"), `${taskId}\n`);
  return dir;
}

export function credentialState(home, refs, env = process.env) {
  const path = join(home, ".credentials.yaml");
  const raw = existsSync(path) ? readFileSync(path, "utf8") : "";
  return Object.fromEntries(refs.map((ref) => {
    const present = Boolean(env[ref]) || new RegExp(`^\\s*${escapeRegExp(ref)}\\s*:`, "mu").test(raw);
    return [ref, present ? "present" : "missing"];
  }));
}

export function credentialValue(home, ref, env = process.env) {
  if (env[ref]) return env[ref];
  const path = join(home, ".credentials.yaml");
  if (!existsSync(path)) return null;
  const match = readFileSync(path, "utf8").match(new RegExp(`^\\s*${escapeRegExp(ref)}\\s*:\\s*(.+?)\\s*$`, "mu"));
  if (!match) return null;
  const value = match[1].trim().replace(/^(['"])(.*)\1$/u, "$2");
  return value && value !== "null" ? value : null;
}

function copyCredentialSubset(sourceHome, targetHome, refs) {
  const lines = [];
  for (const ref of [...new Set(refs)]) {
    // Environment values are inherited by the child process and need not be copied to disk.
    if (process.env[ref]) continue;
    const value = credentialValue(sourceHome, ref, {});
    if (value != null) lines.push(`${ref}: ${JSON.stringify(value)}`);
  }
  if (lines.length) writeFileSync(join(targetHome, ".credentials.yaml"), `${lines.join("\n")}\n`);
}

function assertInside(path, root) {
  if (path !== root && !path.startsWith(root + sep)) throw new Error(`路径越界: ${path}`);
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function toPatchYaml(rows) {
  const lines = [];
  for (const row of rows) {
    lines.push(`- id: ${row.id}`);
    if (row.disabled != null) lines.push(`  disabled: ${row.disabled ? "true" : "false"}`);
  }
  return `${lines.join("\n")}\n`;
}
